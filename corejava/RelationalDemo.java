class RelationalDemo{
    public static void main(String args[]){
	     int  first=7;
		 int  second=12;
		 
		 System.out.println(first==second);
		 System.out.println(first!=second);
		 System.out.println(first>second);
		 System.out.println(first>=second);
		 System.out.println(first<second);
		 System.out.println(first<=second); 
		 
	}	 
}