class BitwiseDemo{
		public static void main(String args[]){
			int first = 12;
			int second = 25;
			int third = 8;
			
			System.out.println(first & second);
			System.out.println(first | second);
			System.out.println(first ^ second);
			System.out.println(third>>2);
			System.out.println(third<<3);
		}
	}
			