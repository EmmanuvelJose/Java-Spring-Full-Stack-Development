class AssignmentDemo{
	public static void main(String args[]){	
      int a=20;
      System.out.println(a+=2);  //20+2=22
      System.out.println(a-=3);  //22-3=19
      System.out.println(a*=2);  //19*2=38
      System.out.println(a/=2);  //38/2=19
	  System.out.println(a%=2);  //19%2=1
	}
}