class StringLength{
	public static void main(String[] args){
		
		String[] name={"Jose","Leena","Dona","Sona","Emmanuvel"};
		
		for(int i=0;i<name.length;i++){
			System.out.println(name[i]);
		}
		
		System.out.println(" ");
		
		for(String s : name){
			System.out.println(s);
		}
	}
}